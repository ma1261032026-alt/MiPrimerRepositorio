# Declalar una variable con la cadena "elefante"

cadena = "elefante"

# Eliminar espacios en blanco a ambos extremos
cadena_limpia = cadena.strip()

# Cuenta y muestra cuantas veces se repite la letra "e"

conteo_e = cadena_limpia.count("e")
print(f"Texto limpio:´{cadena_limpia}´, Conteo de ´e´: {conteo_e}")


